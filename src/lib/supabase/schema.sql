/*
AI Marketing Agent database schema for Supabase PostgreSQL
-----------------------------------------------------------
public.users rows are not automatically created when someone signs up through Supabase Auth
so we need to insert them or add a signup trigger. Also, the shared research tables and tags 
table currently have no client-access RLS policies, so browser-side Supabase requests won't 
be able to use them until we define appropriate access rules.
*/
BEGIN;

CREATE TABLE public.users (
                              id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
                              name varchar,
                              created_at timestamptz DEFAULT now()
);

CREATE TABLE public.user_channels (
                                      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
                                      youtube_channel_id varchar NOT NULL,
                                      name varchar,
                                      subscribers bigint,
                                      queried_at timestamptz DEFAULT now(),
                                      CONSTRAINT user_channels_user_youtube_unique UNIQUE (user_id, youtube_channel_id)
);

CREATE TABLE public.user_videos (
                                    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                    user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
                                    youtube_video_id varchar NOT NULL,
                                    channel_id bigint REFERENCES public.user_channels(id) ON DELETE SET NULL,
                                    title varchar NOT NULL,
                                    thumbnail varchar,
                                    description varchar,
                                    created_at timestamptz DEFAULT now(),
                                    CONSTRAINT user_videos_user_youtube_unique UNIQUE (user_id, youtube_video_id)
);

CREATE TABLE public.user_video_statistics (
                                              id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                              user_video_id bigint NOT NULL REFERENCES public.user_videos(id) ON DELETE CASCADE,
                                              views bigint,
                                              likes bigint,
                                              comments bigint,
                                              queried_at timestamptz DEFAULT now()
);

CREATE TABLE public.research_channels (
                                          id varchar PRIMARY KEY,
                                          name varchar,
                                          subscribers bigint,
                                          queried_at timestamptz DEFAULT now()
);

CREATE TABLE public.research_videos (
                                        id varchar PRIMARY KEY,
                                        channel_id varchar NOT NULL REFERENCES public.research_channels(id),
                                        title varchar NOT NULL,
                                        thumbnail varchar,
                                        description varchar,
                                        published_at timestamptz
);

CREATE TABLE public.research_video_statistics (
                                                  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                  video_id varchar NOT NULL REFERENCES public.research_videos(id) ON DELETE CASCADE,
                                                  views bigint,
                                                  likes bigint,
                                                  comments bigint,
                                                  queried_at timestamptz DEFAULT now()
);

CREATE TABLE public.research_video_features (
                                                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                video_id varchar NOT NULL UNIQUE REFERENCES public.research_videos(id) ON DELETE CASCADE,
                                                ai_description varchar
);

CREATE TABLE public.tags (
                             id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             name varchar NOT NULL UNIQUE,
                             created_at timestamptz DEFAULT now()
);

CREATE TABLE public.user_video_tags (
                                        user_video_id bigint NOT NULL REFERENCES public.user_videos(id) ON DELETE CASCADE,
                                        tag_id bigint NOT NULL REFERENCES public.tags(id) ON DELETE CASCADE,
                                        confidence numeric,
                                        PRIMARY KEY (user_video_id, tag_id)
);

CREATE TABLE public.research_video_tags (
                                            research_video_id varchar NOT NULL REFERENCES public.research_videos(id) ON DELETE CASCADE,
                                            tag_id bigint NOT NULL REFERENCES public.tags(id) ON DELETE CASCADE,
                                            PRIMARY KEY (research_video_id, tag_id)
);

-- Foreign-key and query-supporting indexes
CREATE INDEX idx_user_videos_channel_id ON public.user_videos(channel_id);
CREATE INDEX idx_user_video_statistics_video_time ON public.user_video_statistics(user_video_id, queried_at DESC);
CREATE INDEX idx_research_videos_channel_id ON public.research_videos(channel_id);
CREATE INDEX idx_research_video_statistics_video_time ON public.research_video_statistics(video_id, queried_at DESC);
CREATE INDEX idx_user_video_tags_tag_id ON public.user_video_tags(tag_id);
CREATE INDEX idx_research_video_tags_tag_id ON public.research_video_tags(tag_id);

-- Enable RLS on every table exposed through the public schema.
-- Policies are defined for user-owned data below. Research data remains
-- inaccessible to client roles until you explicitly add policies.
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_channels ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_videos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_video_statistics ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.research_channels ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.research_videos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.research_video_statistics ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.research_video_features ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tags ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_video_tags ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.research_video_tags ENABLE ROW LEVEL SECURITY;

CREATE POLICY users_own_rows ON public.users
    FOR ALL TO authenticated
    USING (id = (select auth.uid()))
    WITH CHECK (id = (select auth.uid()));

CREATE POLICY user_channels_own_rows ON public.user_channels
    FOR ALL TO authenticated
    USING (user_id = (select auth.uid()))
    WITH CHECK (user_id = (select auth.uid()));

CREATE POLICY user_videos_own_rows ON public.user_videos
    FOR ALL TO authenticated
    USING (user_id = (select auth.uid()))
    WITH CHECK (
        user_id = (select auth.uid())
        AND (
            channel_id IS NULL
            OR EXISTS (
                SELECT 1 FROM public.user_channels c
                WHERE c.id = channel_id AND c.user_id = (select auth.uid())
            )
        )
    );

CREATE POLICY user_video_statistics_own_rows ON public.user_video_statistics
    FOR ALL TO authenticated
    USING (EXISTS (
        SELECT 1 FROM public.user_videos v
        WHERE v.id = user_video_id AND v.user_id = (select auth.uid())
    ))
    WITH CHECK (EXISTS (
        SELECT 1 FROM public.user_videos v
        WHERE v.id = user_video_id AND v.user_id = (select auth.uid())
    ));

CREATE POLICY user_video_tags_own_rows ON public.user_video_tags
    FOR ALL TO authenticated
    USING (EXISTS (
        SELECT 1 FROM public.user_videos v
        WHERE v.id = user_video_id AND v.user_id = (select auth.uid())
    ))
    WITH CHECK (EXISTS (
        SELECT 1 FROM public.user_videos v
        WHERE v.id = user_video_id AND v.user_id = (select auth.uid())
    ));
-- ============================================================
-- Automatically create a public.users row on signup
-- ============================================================
-- Supabase Auth inserts into auth.users, which the application cannot
-- write to directly. Every user-owned table references public.users(id),
-- so without a matching row there a signed-up account cannot save
-- channels, videos, statistics or tags at all.
--
-- SECURITY DEFINER runs the function as its owner rather than as the
-- signing-up user, who has no privileges on public.users.
-- SET search_path = '' forces fully qualified names, so the function
-- cannot be redirected to a different schema.

CREATE FUNCTION public.handle_new_user()
    RETURNS trigger
    LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
INSERT INTO public.users (id, name)
VALUES (
           NEW.id,
           COALESCE(
                   NEW.raw_user_meta_data ->> 'name',
            split_part(NEW.email, '@', 1)
        )
       )
    ON CONFLICT (id) DO NOTHING;

RETURN NEW;
END;
$$;

CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_new_user();

-- Backfill accounts that signed up before the trigger existed.
-- Without this, anyone already using the dashboard still has no
-- public.users row.
INSERT INTO public.users (id, name)
SELECT
    u.id,
    COALESCE(
            u.raw_user_meta_data ->> 'name',
        split_part(u.email, '@', 1)
    )
FROM auth.users u
    ON CONFLICT (id) DO NOTHING;

COMMIT;