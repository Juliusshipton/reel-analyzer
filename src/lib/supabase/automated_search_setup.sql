BEGIN;

CREATE TABLE IF NOT EXISTS public.automated_search_configs (
    search_category varchar PRIMARY KEY,
    search_query varchar NOT NULL,
    enabled boolean NOT NULL DEFAULT false,
    frequency varchar NOT NULL
        CHECK (frequency IN ('daily', 'weekly', 'monthly')),
    filters jsonb NOT NULL DEFAULT '{}'::jsonb,
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT automated_search_configs_category_check
        CHECK (search_category IN ('Gaming', 'Food', 'Fitness', 'Education'))
);

ALTER TABLE public.automated_search_configs ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS automated_search_configs_own_rows
    ON public.automated_search_configs;
DROP POLICY IF EXISTS automated_search_configs_shared_access
    ON public.automated_search_configs;
DROP POLICY IF EXISTS automated_search_configs_authenticated_read
    ON public.automated_search_configs;
DROP POLICY IF EXISTS automated_search_configs_authenticated_insert
    ON public.automated_search_configs;
DROP POLICY IF EXISTS automated_search_configs_authenticated_update
    ON public.automated_search_configs;

CREATE POLICY automated_search_configs_authenticated_read
    ON public.automated_search_configs
    FOR SELECT TO authenticated
    USING (true);

CREATE POLICY automated_search_configs_authenticated_insert
    ON public.automated_search_configs
    FOR INSERT TO authenticated
    WITH CHECK (true);

CREATE POLICY automated_search_configs_authenticated_update
    ON public.automated_search_configs
    FOR UPDATE TO authenticated
    USING (true)
    WITH CHECK (true);

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'automated_search_results'
          AND column_name = 'user_id'
    ) THEN
        DROP TABLE public.automated_search_results;
    END IF;
END;
$$;

DROP TABLE IF EXISTS public.automated_search_results_legacy;

CREATE TABLE IF NOT EXISTS public.automated_search_results (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    search_query varchar NOT NULL,
    video_id varchar NOT NULL,
    title varchar NOT NULL,
    channel varchar NOT NULL,
    thumbnail varchar NOT NULL,
    views bigint,
    likes bigint,
    comments bigint,
    stored_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_automated_search_results_video_time
    ON public.automated_search_results(video_id, stored_at DESC);

ALTER TABLE public.automated_search_results ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS automated_search_results_own_rows
    ON public.automated_search_results;

DO $$
BEGIN
    IF to_regclass('public.research_channels') IS NOT NULL THEN
        EXECUTE 'DROP POLICY IF EXISTS research_channels_shared_access ON public.research_channels';
    END IF;
    IF to_regclass('public.research_videos') IS NOT NULL THEN
        EXECUTE 'DROP POLICY IF EXISTS research_videos_shared_access ON public.research_videos';
    END IF;
    IF to_regclass('public.research_video_statistics') IS NOT NULL THEN
        EXECUTE 'DROP POLICY IF EXISTS research_video_statistics_shared_access ON public.research_video_statistics';
    END IF;
END;
$$;

NOTIFY pgrst, 'reload schema';

COMMIT;
