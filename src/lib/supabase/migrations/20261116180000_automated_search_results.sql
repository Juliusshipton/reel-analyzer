CREATE TABLE public.automated_search_results (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    search_category varchar NOT NULL,
    search_query varchar NOT NULL,
    video_id varchar NOT NULL,
    title varchar NOT NULL,
    channel varchar NOT NULL,
    thumbnail varchar NOT NULL,
    views bigint,
    likes bigint,
    comments bigint,
    stored_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_automated_search_results_user_time
    ON public.automated_search_results(user_id, stored_at DESC);

ALTER TABLE public.automated_search_results ENABLE ROW LEVEL SECURITY;

CREATE POLICY automated_search_results_own_rows ON public.automated_search_results
    FOR ALL TO authenticated
    USING (user_id = (select auth.uid()))
    WITH CHECK (user_id = (select auth.uid()));
